#!/usr/bin/env python3
"""Generate the complete binary16-input/binary16-output SiLU ROM offline."""
from pathlib import Path
import argparse,hashlib
import numpy as np
ROOT=Path(__file__).resolve().parents[1];HEADER=ROOT/'src/sst/elements/golem/sfu/silu_lut_tables.h'
def render():
 bits=np.arange(65536,dtype='<u2');x=bits.view('<f2').astype('<f4')
 with np.errstate(over='ignore',invalid='ignore',divide='ignore'):
  values=(x/(np.float32(1.)+np.exp(-x))).astype('<f2').view('<u2')
 lines=['// Generated by scripts/generate_silu_lut.py. Do not edit.','#ifndef SST_GOLEM_SFU_SILU_LUT_TABLES_H','#define SST_GOLEM_SFU_SILU_LUT_TABLES_H','#include <cstdint>','namespace SST { namespace Golem { namespace SFURom {','inline constexpr uint16_t SiLU[65536] = {']
 for i in range(0,65536,16):lines.append('    '+', '.join(f'0x{v:04x}' for v in values[i:i+16])+',')
 lines += ['};','inline constexpr uint64_t SiLUBytes = sizeof(SiLU);','} } }','#endif','']
 return '\n'.join(lines),hashlib.sha256(values.tobytes()).hexdigest()
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();text,digest=render()
 if a.check:
  if not HEADER.exists() or HEADER.read_text()!=text:raise SystemExit('SiLU ROM is stale; regenerate explicitly')
  print('PASS: SiLU ROM is reproducible',digest)
 else:HEADER.write_text(text);print({'entries':65536,'bytes':131072,'sha256':digest,'header':str(HEADER)})
if __name__=='__main__':main()
